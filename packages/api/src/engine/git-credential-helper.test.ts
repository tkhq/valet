/**
 * Golden tests for the in-sandbox git credential script generators
 * (GitHub/repo integration plan, Task 8). These pin the exact script text
 * so a shape change is a visible diff, and enforce the security invariant
 * that NO token material is ever embedded — the sandbox token is read from
 * `/etc/valet/creds/token` (the creds mount) first, then from the
 * `$VALET_SANDBOX_TOKEN` environment variable as a fallback. The only
 * interpolated value is `apiUrl`, which is not secret.
 */
import { spawn, spawnSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { createServer } from "node:http";
import { once } from "node:events";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { appSignedGitWrapperScript, gitCredentialHelperScript, ghWrapperScript, REAL_GIT_PATH } from "./git-credential-helper.js";

const API_URL = "http://valet-api.example.com";

describe("gitCredentialHelperScript", () => {
  it("matches the golden", () => {
    expect(gitCredentialHelperScript(API_URL)).toBe(`#!/bin/sh
# git-credential-valet — resolves a per-owner git token from the Valet API.
# Generated by @valet/api (engine/git-credential-helper.ts); installed by
# sandbox prep. Only the 'get' verb does work; 'store'/'erase' are no-ops.
# No token material is embedded here: the sandbox token is read from the
# creds mount (/etc/valet/creds/token) first, then $VALET_SANDBOX_TOKEN.
set -eu

[ "\${1:-}" = "get" ] || exit 0

host=
path=
while IFS='=' read -r key value; do
  case "$key" in
    host) host=$value ;;
    path) path=$value ;;
  esac
done

owner=\${path%%/*}
repo=
case "$path" in
  */*) repo=\${path#*/}; repo=\${repo%%/*}; repo=\${repo%.git} ;;
esac
[ -n "$owner" ] || exit 0
tok=$(cat /etc/valet/creds/token 2>/dev/null) || tok=
[ -n "$tok" ] || tok=\${VALET_SANDBOX_TOKEN:-}
# Degraded paths warn on stderr (git shows credential-helper stderr) but
# still exit 0 so PUBLIC repos keep working anonymously. Without the
# warning, a revoked/missing sandbox token surfaces only as a cryptic
# "unable to read <sha>" when a blobless clone lazily fetches blobs.
if [ -z "$tok" ]; then
  echo "git-credential-valet: no sandbox token found — using no credentials for $host/$owner. If this repository needs auth, restart the session." >&2
  exit 0
fi

resp=$(curl --max-time 10 -fsS \\
  -X POST "http://valet-api.example.com/api/sandbox/git-credential" \\
  -H "x-valet-sandbox: $tok" \\
  -H "Content-Type: application/json" \\
  -d "{\\"host\\":\\"$host\\",\\"owner\\":\\"$owner\\",\\"repo\\":\\"$repo\\"}") || {
  echo "git-credential-valet: credential request to the Valet API failed — using no credentials for $host/$owner. If git then fails to fetch, restart the session to refresh sandbox credentials." >&2
  exit 0
}

username=$(printf '%s' "$resp" | sed -n 's/.*"username"[[:space:]]*:[[:space:]]*"\\([^"]*\\)".*/\\1/p')
password=$(printf '%s' "$resp" | sed -n 's/.*"password"[[:space:]]*:[[:space:]]*"\\([^"]*\\)".*/\\1/p')

[ -n "$username" ] || exit 0
[ -n "$password" ] || exit 0

printf 'username=%s\\n' "$username"
printf 'password=%s\\n' "$password"
`);
  });

  it("uses the x-valet-sandbox header, not Authorization: Bearer", () => {
    const script = gitCredentialHelperScript(API_URL);
    expect(script).toContain("x-valet-sandbox: $tok");
    expect(script).not.toContain("Authorization");
  });

  it("reads the creds mount before falling back to the env variable", () => {
    const script = gitCredentialHelperScript(API_URL);
    // Creds mount read must precede the env fallback assignment.
    const credsReadAt = script.indexOf("cat /etc/valet/creds/token");
    const envFallbackAt = script.indexOf("VALET_SANDBOX_TOKEN:-}");
    expect(credsReadAt).toBeGreaterThan(-1);
    expect(envFallbackAt).toBeGreaterThan(-1);
    expect(credsReadAt).toBeLessThan(envFallbackAt);
  });

  it("embeds only the API URL as non-secret — never literal token material", () => {
    const script = gitCredentialHelperScript(API_URL);
    // The creds mount path and env var name appear; no literal token values.
    expect(script).toContain("/etc/valet/creds/token");
    expect(script).toContain("VALET_SANDBOX_TOKEN");
    // No literal sandbox token material (`st_` prefix) or GitHub token
    // prefixes should ever be baked in.
    expect(script).not.toMatch(/st_[0-9a-f]/);
    expect(script).not.toMatch(/gh[pousr]_/);
  });

  it("no-ops non-get verbs and derives owner from the path's first segment", () => {
    const script = gitCredentialHelperScript(API_URL);
    expect(script).toContain('[ "${1:-}" = "get" ] || exit 0');
    expect(script).toContain("owner=${path%%/*}");
  });
});

describe("ghWrapperScript", () => {
  it("installs deterministic credential and PR-observation paths", () => {
    const script = ghWrapperScript(API_URL);
    expect(script).toContain(`${API_URL}/api/sandbox/git-credential`);
    expect(script).toContain(`${API_URL}/api/sandbox/git-pr/observe`);
    expect(script).toContain('"pr" ] && [ "${2:-}" = "create"');
  });

  it("execs the real gh (never itself) with token via env only", () => {
    const script = ghWrapperScript(API_URL);
    expect(script).toContain('exec "$real" "$@"');
    expect(script).toContain('exec env GH_TOKEN="$token" "$real" "$@"');
    // The shim installs at /usr/local/bin/gh; the PATH scan must skip that
    // dir or the shim would exec itself forever.
    expect(script).toContain('case "$d" in /usr/local/bin|"") continue ;; esac');
  });

  it("caller auth wins: env tokens and hosts.yml short-circuit before any fetch", () => {
    const script = ghWrapperScript(API_URL);
    const fetchAt = script.indexOf("curl");
    expect(script.indexOf("GH_TOKEN:-")).toBeLessThan(fetchAt);
    expect(script.indexOf("GITHUB_TOKEN:-")).toBeLessThan(fetchAt);
    expect(script.indexOf("hosts.yml")).toBeLessThan(fetchAt);
  });

  it("requests purpose=api so repo-independent gh calls hit the user-first ladder", () => {
    expect(ghWrapperScript(API_URL)).toContain('\\"purpose\\":\\"api\\"');
  });

  it("reads the creds mount before falling back to the env variable", () => {
    const script = ghWrapperScript(API_URL);
    // Creds mount read must precede the env fallback assignment.
    const credsReadAt = script.indexOf("cat /etc/valet/creds/token");
    const envFallbackAt = script.indexOf("VALET_SANDBOX_TOKEN:-}");
    expect(credsReadAt).toBeGreaterThan(-1);
    expect(envFallbackAt).toBeGreaterThan(-1);
    expect(credsReadAt).toBeLessThan(envFallbackAt);
  });

  it("never embeds token material", () => {
    const script = ghWrapperScript(API_URL);
    // The creds mount path and env var name appear; no literal token values.
    expect(script).toContain("/etc/valet/creds/token");
    expect(script).toContain("VALET_SANDBOX_TOKEN");
    expect(script).not.toMatch(/st_[0-9a-f]/);
    expect(script).not.toMatch(/gh[pousr]_/);
  });
});


describe("appSignedGitWrapperScript", () => {
  it("executes typed refusal paths before guessing a destination", () => {
    const dir = mkdtempSync(join(tmpdir(), "valet-app-git-"));
    try {
      const wrapper = join(dir, "git"); writeFileSync(wrapper, appSignedGitWrapperScript(API_URL), { mode: 0o755 });
      const result = spawnSync(process.execPath, [wrapper, "push", "origin", ":main"], { encoding: "utf8" });
      expect(result.status).toBe(2); expect(result.stderr).toContain("branch deletion and empty refspec sides");
    } finally { rmSync(dir, { recursive: true, force: true }); }
  });

  it.each([
    ["HEAD", "refs/heads/feature", false, "normal"],
    ["feature", "refs/heads/feature", false, "normal"],
    ["feature:refs/heads/review", "refs/heads/review", false, "normal"],
    ["feature:refs/heads/new-branch", "refs/heads/new-branch", true, "normal"],
    ["main:refs/heads/review", "refs/heads/review", false, "normal"],
    ["feature:refs/heads/stale-lock", "refs/heads/stale-lock", true, "stale"],
    ["feature:refs/heads/live-lock", "refs/heads/live-lock", true, "live"],
    ["feature:refs/heads/api-error", "refs/heads/api-error", true, "error"],
  ] as const)("executes push parsing and lock hygiene for %s (%s)", async (refspec, expectedRef, createRef, lockMode) => {
    const dir = mkdtempSync(join(tmpdir(), "valet-app-git-success-"));
    const requests: Array<Record<string, unknown>> = [];
    const server = createServer((request, response) => {
      let body = "";
      request.setEncoding("utf8");
      request.on("data", (chunk) => { body += chunk; });
      request.on("end", () => {
        if (request.url === "/api/sandbox/git-push") requests.push(JSON.parse(body) as Record<string, unknown>);
        const failed = lockMode === "error" && request.url === "/api/sandbox/git-push";
        response.writeHead(failed ? 500 : 200, { "content-type": "application/json" });
        response.end(failed ? '{"error":"fixture replay failed"}' : request.url?.endsWith("/reconcile") ? "{}" : '{"operationId":"gpo-test","signedHeadSha":"signedsha"}');
      });
    });
    server.listen(0, "127.0.0.1");
    await once(server, "listening");
    try {
      const address = server.address();
      if (!address || typeof address === "string") throw new Error("test server did not bind");
      const fakeGit = join(dir, "git-real");
      writeFileSync(fakeGit, `#!/bin/sh
printf '%s\\n' "$*" >> "$TEST_GIT_LOG"
case "$1" in
  rev-parse)
    case "$*" in
      *--is-shallow-repository*) echo false ;;
      *--symbolic-full-name*) echo "refs/heads/$3" ;;
      *refs/valet/signed/*) echo signedsha ;;
      *"signedsha^{tree}"*) [ "$TEST_SOURCE_MAIN" = 1 ] && echo tree-main || echo tree1 ;;
      *"mainsha^{tree}"*) echo tree-main ;;
      *"^{tree}"*) echo tree1 ;;
      *--absolute-git-dir*) echo "$TEST_GIT_DIR" ;;
      *refs/heads/main*) echo mainsha ;;
      *HEAD*) [ "$TEST_SOURCE_MAIN" = 1 ] && echo featuresha || echo localsha ;;
      *) echo localsha ;;
    esac ;;
  symbolic-ref) echo refs/heads/feature ;;
  remote) echo https://github.com/acme/widgets.git ;;
  ls-remote) [ "$TEST_NEW_BRANCH" = 1 ] || printf 'oldsha\\t%s\\n' "$3" ;;
  fetch|update-ref|reset|branch|status) ;;
  write-tree) echo tree1 ;;
  rev-list) echo localsha ;;
  cat-file)
    case "$2" in
      commit) printf 'tree tree1\\nparent oldsha\\n\\nMessage\\n' ;;
      -e) ;;
      -t) echo commit ;;
    esac ;;
  *) exit 1 ;;
esac
`, { mode: 0o755 });
      const wrapper = join(dir, "git");
      const script = appSignedGitWrapperScript(`http://127.0.0.1:${address.port}`)
        .replace(`const real = ${JSON.stringify(REAL_GIT_PATH)};`, `const real = ${JSON.stringify(fakeGit)};`);
      writeFileSync(wrapper, script, { mode: 0o755 });
      const lockPath = join(dir, "valet-reconcile.lock");
      if (lockMode === "stale") writeFileSync(lockPath, JSON.stringify({ pid: 2_147_483_647, createdAt: 0, token: "stale" }));
      if (lockMode === "live") writeFileSync(lockPath, JSON.stringify({ pid: process.pid, createdAt: Date.now(), token: "peer" }));
      const result = await new Promise<{ status: number | null; stderr: string }>((resolve) => {
        const child = spawn(process.execPath, [wrapper, "push", "origin", refspec], {
          env: { ...process.env, VALET_SANDBOX_TOKEN: "test-token", TEST_NEW_BRANCH: createRef ? "1" : "0", TEST_SOURCE_MAIN: refspec.startsWith("main:") ? "1" : "0", TEST_GIT_DIR: dir, TEST_GIT_LOG: join(dir, "git.log") },
        });
        let stderr = "";
        child.stderr.setEncoding("utf8");
        child.stderr.on("data", (chunk) => { stderr += chunk; });
        child.on("close", (status) => resolve({ status, stderr }));
      });
      if (lockMode === "live") {
        expect(result.status).toBe(2);
        expect(result.stderr).toContain(`reconcile lock ${lockPath} is held by live process ${process.pid}`);
        expect(result.stderr).toContain(`remove ${lockPath} and retry`);
        expect(JSON.parse(readFileSync(lockPath, "utf8"))).toMatchObject({ token: "peer" });
        expect(requests).toHaveLength(0);
        return;
      }
      if (lockMode === "error") {
        expect(result.status).toBe(2);
        expect(result.stderr).toContain("fixture replay failed");
        expect(existsSync(lockPath)).toBe(false);
        return;
      }
      expect(result.status, result.stderr).toBe(0);
      expect(requests).toHaveLength(1);
      expect(requests[0]).toMatchObject({ targetRef: expectedRef, createRef });
      expect(existsSync(lockPath)).toBe(false);
      if (refspec.startsWith("main:")) {
        const calls = readFileSync(join(dir, "git.log"), "utf8");
        expect(calls).toContain("update-ref refs/heads/main signedsha mainsha");
        expect(calls).toContain("rev-parse HEAD");
        expect(calls).toContain("rev-parse mainsha^{tree}");
        expect(calls).not.toContain("reset --soft");
      }
    } finally {
      server.close();
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("bounds blob extraction and names shallow and oversized-object refusals", () => {
    const script = appSignedGitWrapperScript(API_URL);
    expect(script).toContain("maxBuffer: MAX_BLOB_BYTES + 1");
    expect(script).toContain("tracked blob ");
    expect(script).toContain("shallow clones cannot be App-signed");
    expect(script).toContain('destination = sourceRef.slice("refs/heads/".length)');
    expect(script).toContain("/reconcile");
  });

  it("chains non-push commands and routes pushes through host replay without write credentials", () => {
    const script = appSignedGitWrapperScript(`${API_URL}/`);
    expect(script).toContain('args[0] !== "push"');
    expect(script).toContain(`${API_URL}/api/sandbox/git-push`);
    expect(script).toContain("force, delete, tags, mirror, atomic");
    expect(script).toContain("lfsObjects");
    expect(script).not.toMatch(/gh[pousr]_/u);
  });
});

describe("git credential helper execution", () => {
  function runHelper(mountToken: string, mountFails: boolean, envToken: string, expectedToken: string) {
    const dir = mkdtempSync(join(tmpdir(), "valet-git-helper-"));
    try {
      // Simulate the mount without reading or changing the host's /etc directory.
      writeFileSync(join(dir, "cat"), `#!/bin/sh
[ "$TEST_MOUNT_FAILS" = "false" ] || exit 1
printf '%s' "$TEST_MOUNT_TOKEN"
`, { mode: 0o755 });
      writeFileSync(join(dir, "curl"), `#!/bin/sh
for arg do
  if [ "$arg" = "x-valet-sandbox: $TEST_EXPECTED_TOKEN" ]; then
    printf '%s' '{"username":"x-access-token","password":"fake-installation-token"}'
    exit 0
  fi
done
exit 1
`, { mode: 0o755 });
      const helper = join(dir, "helper.sh");
      writeFileSync(helper, gitCredentialHelperScript(API_URL));
      return spawnSync("/bin/sh", [helper, "get"], {
        encoding: "utf8",
        input: "protocol=https\nhost=github.com\npath=tkhq/docs.git\n\n",
        env: {
          PATH: `${dir}:/usr/bin:/bin`,
          VALET_SANDBOX_TOKEN: envToken,
          TEST_MOUNT_TOKEN: mountToken,
          TEST_MOUNT_FAILS: String(mountFails),
          TEST_EXPECTED_TOKEN: expectedToken,
        },
      });
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  }

  it.each([
    { label: "missing or unreadable mount", mountToken: "", mountFails: true, envToken: "fake-env-token", expected: "fake-env-token" },
    { label: "empty mount", mountToken: "", mountFails: false, envToken: "fake-env-token", expected: "fake-env-token" },
    { label: "mounted token takes precedence", mountToken: "fake-mounted-token", mountFails: false, envToken: "fake-env-token", expected: "fake-mounted-token" },
  ])("authenticates with $label", ({ mountToken, mountFails, envToken, expected }) => {
    const result = runHelper(mountToken, mountFails, envToken, expected);
    expect(result.status).toBe(0);
    expect(result.stdout).toBe("username=x-access-token\npassword=fake-installation-token\n");
    expect(result.stderr).toBe("");
  });

  it("warns and continues anonymously when neither token source is available", () => {
    const result = runHelper("", true, "", "must-not-call-credential-api");
    expect(result.status).toBe(0);
    expect(result.stdout).toBe("");
    expect(result.stderr).toContain("git-credential-valet: no sandbox token found");
  });
});
