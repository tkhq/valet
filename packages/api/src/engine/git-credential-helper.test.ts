/**
 * Golden tests for the in-sandbox git credential script generators
 * (GitHub/repo integration plan, Task 8). These pin the exact script text
 * so a shape change is a visible diff, and enforce the security invariant
 * that NO token material is ever embedded — the sandbox token is read from
 * `/etc/valet/creds/token` (the creds mount) first, then from the
 * `$VALET_SANDBOX_TOKEN` environment variable as a fallback. The only
 * interpolated value is `apiUrl`, which is not secret.
 */
import { spawnSync } from "node:child_process";
import { mkdtempSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { gitCredentialHelperScript, ghWrapperScript } from "./git-credential-helper.js";

const API_URL = "http://valet-api.example.com";

describe("gitCredentialHelperScript", () => {
  it("matches the golden", () => {
    expect(gitCredentialHelperScript(API_URL)).toBe(`#!/bin/sh
# git-credential-valet — resolves a per-owner git token from the Valet API.
# Generated by @valet/api (engine/git-credential-helper.ts); installed by
# sandbox prep. Only the 'get' verb does work; 'store'/'erase' are no-ops.
# No token material is embedded here: the sandbox token is read from the
# creds mount (/etc/valet/creds/token) first, then $VALET_SANDBOX_TOKEN.
set -eu

[ "\${1:-}" = "get" ] || exit 0

host=
path=
while IFS='=' read -r key value; do
  case "$key" in
    host) host=$value ;;
    path) path=$value ;;
  esac
done

owner=\${path%%/*}
repo=
case "$path" in
  */*) repo=\${path#*/}; repo=\${repo%%/*}; repo=\${repo%.git} ;;
esac
[ -n "$owner" ] || exit 0
tok=$(cat /etc/valet/creds/token 2>/dev/null) || tok=
[ -n "$tok" ] || tok=\${VALET_SANDBOX_TOKEN:-}
# Degraded paths warn on stderr (git shows credential-helper stderr) but
# still exit 0 so PUBLIC repos keep working anonymously. Without the
# warning, a revoked/missing sandbox token surfaces only as a cryptic
# "unable to read <sha>" when a blobless clone lazily fetches blobs.
if [ -z "$tok" ]; then
  echo "git-credential-valet: no sandbox token found — using no credentials for $host/$owner. If this repository needs auth, restart the session." >&2
  exit 0
fi

resp=$(curl --max-time 10 -fsS \\
  -X POST "http://valet-api.example.com/api/sandbox/git-credential" \\
  -H "x-valet-sandbox: $tok" \\
  -H "Content-Type: application/json" \\
  -d "{\\"host\\":\\"$host\\",\\"owner\\":\\"$owner\\",\\"repo\\":\\"$repo\\"}") || {
  echo "git-credential-valet: credential request to the Valet API failed — using no credentials for $host/$owner. If git then fails to fetch, restart the session to refresh sandbox credentials." >&2
  exit 0
}

username=$(printf '%s' "$resp" | sed -n 's/.*"username"[[:space:]]*:[[:space:]]*"\\([^"]*\\)".*/\\1/p')
password=$(printf '%s' "$resp" | sed -n 's/.*"password"[[:space:]]*:[[:space:]]*"\\([^"]*\\)".*/\\1/p')

[ -n "$username" ] || exit 0
[ -n "$password" ] || exit 0

printf 'username=%s\\n' "$username"
printf 'password=%s\\n' "$password"
`);
  });

  it("uses the x-valet-sandbox header, not Authorization: Bearer", () => {
    const script = gitCredentialHelperScript(API_URL);
    expect(script).toContain("x-valet-sandbox: $tok");
    expect(script).not.toContain("Authorization");
  });

  it("reads the creds mount before falling back to the env variable", () => {
    const script = gitCredentialHelperScript(API_URL);
    // Creds mount read must precede the env fallback assignment.
    const credsReadAt = script.indexOf("cat /etc/valet/creds/token");
    const envFallbackAt = script.indexOf("VALET_SANDBOX_TOKEN:-}");
    expect(credsReadAt).toBeGreaterThan(-1);
    expect(envFallbackAt).toBeGreaterThan(-1);
    expect(credsReadAt).toBeLessThan(envFallbackAt);
  });

  it("embeds only the API URL as non-secret — never literal token material", () => {
    const script = gitCredentialHelperScript(API_URL);
    // The creds mount path and env var name appear; no literal token values.
    expect(script).toContain("/etc/valet/creds/token");
    expect(script).toContain("VALET_SANDBOX_TOKEN");
    // No literal sandbox token material (`st_` prefix) or GitHub token
    // prefixes should ever be baked in.
    expect(script).not.toMatch(/st_[0-9a-f]/);
    expect(script).not.toMatch(/gh[pousr]_/);
  });

  it("no-ops non-get verbs and derives owner from the path's first segment", () => {
    const script = gitCredentialHelperScript(API_URL);
    expect(script).toContain('[ "${1:-}" = "get" ] || exit 0');
    expect(script).toContain("owner=${path%%/*}");
  });
});

describe("ghWrapperScript", () => {
  it("matches the golden", () => {
    expect(ghWrapperScript(API_URL)).toBe(`#!/bin/sh
# gh (Valet shim, also installed as valet-gh) — runs the real 'gh' with a
# Valet-resolved GH_TOKEN when you have not authenticated yourself; your own
# GH_TOKEN/GITHUB_TOKEN or 'gh auth login' always wins. Generated by
# @valet/api (engine/git-credential-helper.ts); installed by sandbox prep.
# No token material is embedded here: the sandbox token is read from the
# creds mount (/etc/valet/creds/token) first, then $VALET_SANDBOX_TOKEN.
set -u

# The real gh: first executable named 'gh' on PATH outside /usr/local/bin
# (this shim's fixed install dir — skipping it prevents self-exec).
real=
oldifs=$IFS
IFS=:
for d in $PATH; do
  case "$d" in /usr/local/bin|"") continue ;; esac
  if [ -x "$d/gh" ]; then real="$d/gh"; break; fi
done
IFS=$oldifs
if [ -z "$real" ]; then
  echo "gh is not installed in this sandbox image" >&2
  exit 127
fi

# Caller-provided auth wins: env token or a completed 'gh auth login'.
if [ -n "\${GH_TOKEN:-}" ] || [ -n "\${GITHUB_TOKEN:-}" ]; then exec "$real" "$@"; fi
if [ -f "\${GH_CONFIG_DIR:-$HOME/.config/gh}/hosts.yml" ]; then exec "$real" "$@"; fi

tok=$(cat /etc/valet/creds/token 2>/dev/null) || tok=
[ -n "$tok" ] || tok=\${VALET_SANDBOX_TOKEN:-}
token=
if [ -n "$tok" ]; then
  remote=$(git config --get remote.origin.url 2>/dev/null)
  owner=$(printf '%s' "$remote" | sed -n 's#.*[/:]\\([^/]*\\)/[^/]*$#\\1#p')
  repo=$(printf '%s' "$remote" | sed -n 's#.*/\\([^/]*\\)$#\\1#p')
  repo=\${repo%.git}
  resp=$(curl --max-time 10 -fsS \\
    -X POST "http://valet-api.example.com/api/sandbox/git-credential" \\
    -H "x-valet-sandbox: $tok" \\
    -H "Content-Type: application/json" \\
    -d "{\\"host\\":\\"github.com\\",\\"owner\\":\\"$owner\\",\\"repo\\":\\"$repo\\",\\"purpose\\":\\"api\\"}" 2>/dev/null) || resp=
  token=$(printf '%s' "$resp" | sed -n 's/.*"password"[[:space:]]*:[[:space:]]*"\\([^"]*\\)".*/\\1/p')
fi

# Signed pull requests: when the organization requires them, 'gh pr create'
# runs only when GitHub shows every commit on the branch as Verified. Valet
# answers 204 for no rule, or the instruction for the agent as plain text.
# Any other answer refuses: a failed lookup must not skip the check.
if [ -n "$token" ] && [ "\${1:-}" = pr ] && { [ "\${2:-}" = create ] || [ "\${2:-}" = new ]; }; then
  ruleFile=$(mktemp)
  code=$(curl --max-time 10 -sS -o "$ruleFile" -w '%{http_code}' -X POST "http://valet-api.example.com/api/sandbox/pull-request-requirement" -H "x-valet-sandbox: $tok" 2>/dev/null) || code=000
  rule=$(cat "$ruleFile")
  rm -f "$ruleFile"
  case "$code" in
    204) rule= ;;
    200) ;;
    *)
      echo "Pull request not opened. Valet could not read the organization's pull request rule (HTTP $code). Try again." >&2
      exit 1 ;;
  esac
  if [ -n "$rule" ]; then
    head= base= nwo= prev=
    for a in "$@"; do
      case "$prev" in -H|--head) head=$a ;; -B|--base) base=$a ;; -R|--repo) nwo=$a ;; esac
      case "$a" in --head=*) head=\${a#--head=} ;; --base=*) base=\${a#--base=} ;; --repo=*) nwo=\${a#--repo=} ;; esac
      prev=$a
    done
    export GH_TOKEN="$token"
    [ -n "$nwo" ] || nwo=$("$real" repo view --json nameWithOwner --jq .nameWithOwner 2>/dev/null)
    [ -n "$head" ] || head=$(git rev-parse --abbrev-ref HEAD 2>/dev/null)
    [ -n "$base" ] || base=$("$real" repo view "$nwo" --json defaultBranchRef --jq .defaultBranchRef.name 2>/dev/null)
    unsigned=$("$real" api "repos/$nwo/compare/$base...$head" --jq 'if .total_commits > (.commits | length) then "more than \\(.commits | length) commits" else [.commits[] | select(.commit.verification.verified | not) | .sha[0:7]] | join(" ") end' 2>&1) || {
      echo "Pull request not opened. Valet could not check the commits from $base to $head: $unsigned" >&2
      exit 1
    }
    if [ -n "$unsigned" ]; then
      echo "Pull request not opened. Commits on $head not Verified on GitHub: $unsigned" >&2
      printf '%s\\n' "$rule" >&2
      exit 1
    fi
  fi
fi

if [ -n "$token" ]; then
  exec env GH_TOKEN="$token" "$real" "$@"
fi
exec "$real" "$@"
`);
  });

  it("execs the real gh (never itself) with token via env only", () => {
    const script = ghWrapperScript(API_URL);
    expect(script).toContain('exec "$real" "$@"');
    expect(script).toContain('exec env GH_TOKEN="$token" "$real" "$@"');
    // The shim installs at /usr/local/bin/gh; the PATH scan must skip that
    // dir or the shim would exec itself forever.
    expect(script).toContain('case "$d" in /usr/local/bin|"") continue ;; esac');
  });

  it("caller auth wins: env tokens and hosts.yml short-circuit before any fetch", () => {
    const script = ghWrapperScript(API_URL);
    const fetchAt = script.indexOf("curl");
    expect(script.indexOf("GH_TOKEN:-")).toBeLessThan(fetchAt);
    expect(script.indexOf("GITHUB_TOKEN:-")).toBeLessThan(fetchAt);
    expect(script.indexOf("hosts.yml")).toBeLessThan(fetchAt);
  });

  it("requests purpose=api so repo-independent gh calls hit the user-first ladder", () => {
    expect(ghWrapperScript(API_URL)).toContain('\\"purpose\\":\\"api\\"');
  });

  it("reads the creds mount before falling back to the env variable", () => {
    const script = ghWrapperScript(API_URL);
    // Creds mount read must precede the env fallback assignment.
    const credsReadAt = script.indexOf("cat /etc/valet/creds/token");
    const envFallbackAt = script.indexOf("VALET_SANDBOX_TOKEN:-}");
    expect(credsReadAt).toBeGreaterThan(-1);
    expect(envFallbackAt).toBeGreaterThan(-1);
    expect(credsReadAt).toBeLessThan(envFallbackAt);
  });

  it("never embeds token material", () => {
    const script = ghWrapperScript(API_URL);
    // The creds mount path and env var name appear; no literal token values.
    expect(script).toContain("/etc/valet/creds/token");
    expect(script).toContain("VALET_SANDBOX_TOKEN");
    expect(script).not.toMatch(/st_[0-9a-f]/);
    expect(script).not.toMatch(/gh[pousr]_/);
  });
});


describe("gh shim signed pull request check", () => {
  const RULE = "This organization requires signed commits for pull requests. Sign the commits.";

  /** Runs the shim with stand-ins for curl, git, and the real gh. */
  function runShim(args: string[], opts: { rule?: string; ruleCode?: string; unsigned?: string; compareFails?: boolean } = {}) {
    const dir = mkdtempSync(join(tmpdir(), "valet-gh-shim-"));
    const bin = join(dir, "bin");
    const realDir = join(dir, "real");
    const log = join(dir, "log");
    try {
      spawnSync("mkdir", ["-p", bin, realDir]);
      writeFileSync(join(bin, "curl"), `#!/bin/sh
echo "curl $*" >> "$TEST_LOG"
case "$*" in
  *pull-request-requirement*)
    [ "$TEST_RULE_CODE" = fail ] && exit 7
    out= prev=
    for a in "$@"; do [ "$prev" = "-o" ] && out=$a; prev=$a; done
    printf '%s' "$TEST_RULE" > "$out"
    if [ -n "$TEST_RULE_CODE" ]; then printf '%s' "$TEST_RULE_CODE"; elif [ -n "$TEST_RULE" ]; then printf 200; else printf 204; fi ;;
  *git-credential*) printf '%s' '{"username":"x-access-token","password":"fake-token"}' ;;
esac
`, { mode: 0o755 });
      writeFileSync(join(bin, "git"), `#!/bin/sh
case "$*" in
  "config --get remote.origin.url") echo https://github.com/acme/app.git ;;
  "rev-parse --abbrev-ref HEAD") echo feature ;;
esac
`, { mode: 0o755 });
      writeFileSync(join(realDir, "gh"), `#!/bin/sh
case "$1 $2" in
  "repo view") case "$*" in *nameWithOwner*) echo acme/app ;; *) echo main ;; esac ;;
  "api "*) echo "compare $2" >> "$TEST_LOG"
    if [ -n "$TEST_COMPARE_FAILS" ]; then echo "HTTP 404: Not Found"; exit 1; fi
    printf '%s\\n' "$TEST_UNSIGNED" ;;
  *) echo "ran $* with $GH_TOKEN" ;;
esac
`, { mode: 0o755 });
      const shim = join(dir, "gh.sh");
      writeFileSync(shim, ghWrapperScript(API_URL));
      const result = spawnSync("/bin/sh", [shim, ...args], {
        encoding: "utf8",
        env: {
          PATH: `${bin}:${realDir}:/usr/bin:/bin`,
          HOME: dir,
          VALET_SANDBOX_TOKEN: "fake-sandbox-token",
          TEST_LOG: log,
          TEST_RULE: opts.rule ?? "",
          TEST_RULE_CODE: opts.ruleCode ?? "",
          TEST_UNSIGNED: opts.unsigned ?? "",
          TEST_COMPARE_FAILS: opts.compareFails ? "1" : "",
        },
      });
      const calls = spawnSync("cat", [log], { encoding: "utf8" }).stdout;
      return { ...result, calls };
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  }

  it("opens the pull request when the org has no rule", () => {
    const r = runShim(["pr", "create", "--fill"]);
    expect(r.status).toBe(0);
    expect(r.stdout).toBe("ran pr create --fill with fake-token\n");
    expect(r.calls).not.toContain("compare");
  });

  it("opens the pull request when every commit is Verified", () => {
    const r = runShim(["pr", "create", "--fill"], { rule: RULE });
    expect(r.status).toBe(0);
    expect(r.stdout).toBe("ran pr create --fill with fake-token\n");
    expect(r.calls).toContain("compare repos/acme/app/compare/main...feature");
  });

  it("refuses with the commits and the rule when a commit is not Verified", () => {
    const r = runShim(["pr", "create", "--fill"], { rule: RULE, unsigned: "abc1234 def5678" });
    expect(r.status).toBe(1);
    expect(r.stdout).toBe("");
    expect(r.stderr).toContain("Pull request not opened. Commits on feature not Verified on GitHub: abc1234 def5678");
    expect(r.stderr).toContain(RULE);
  });

  it("compares the base, head, and repository the flags name", () => {
    const r = runShim(["pr", "new", "-R", "acme/other", "--base", "dev", "--head=topic"], { rule: RULE });
    expect(r.status).toBe(0);
    expect(r.calls).toContain("compare repos/acme/other/compare/dev...topic");
  });

  it("refuses when the comparison fails", () => {
    const r = runShim(["pr", "create", "--fill"], { rule: RULE, compareFails: true });
    expect(r.status).toBe(1);
    expect(r.stderr).toContain("Valet could not check the commits from main to feature: HTTP 404: Not Found");
  });

  it.each([
    { label: "an error status", ruleCode: "500", shown: "HTTP 500" },
    { label: "a failed request", ruleCode: "fail", shown: "HTTP 000" },
  ])("refuses when the rule lookup returns $label", ({ ruleCode, shown }) => {
    const r = runShim(["pr", "create", "--fill"], { ruleCode });
    expect(r.status).toBe(1);
    expect(r.stdout).toBe("");
    expect(r.stderr).toContain(`Pull request not opened. Valet could not read the organization's pull request rule (${shown}). Try again.`);
    expect(r.calls).not.toContain("compare");
  });

  it("asks for the rule only for gh pr create", () => {
    const r = runShim(["pr", "list"], { rule: RULE });
    expect(r.status).toBe(0);
    expect(r.calls).not.toContain("pull-request-requirement");
  });
});

describe("git credential helper execution", () => {
  function runHelper(mountToken: string, mountFails: boolean, envToken: string, expectedToken: string) {
    const dir = mkdtempSync(join(tmpdir(), "valet-git-helper-"));
    try {
      // Simulate the mount without reading or changing the host's /etc directory.
      writeFileSync(join(dir, "cat"), `#!/bin/sh
[ "$TEST_MOUNT_FAILS" = "false" ] || exit 1
printf '%s' "$TEST_MOUNT_TOKEN"
`, { mode: 0o755 });
      writeFileSync(join(dir, "curl"), `#!/bin/sh
for arg do
  if [ "$arg" = "x-valet-sandbox: $TEST_EXPECTED_TOKEN" ]; then
    printf '%s' '{"username":"x-access-token","password":"fake-installation-token"}'
    exit 0
  fi
done
exit 1
`, { mode: 0o755 });
      const helper = join(dir, "helper.sh");
      writeFileSync(helper, gitCredentialHelperScript(API_URL));
      return spawnSync("/bin/sh", [helper, "get"], {
        encoding: "utf8",
        input: "protocol=https\nhost=github.com\npath=tkhq/docs.git\n\n",
        env: {
          PATH: `${dir}:/usr/bin:/bin`,
          VALET_SANDBOX_TOKEN: envToken,
          TEST_MOUNT_TOKEN: mountToken,
          TEST_MOUNT_FAILS: String(mountFails),
          TEST_EXPECTED_TOKEN: expectedToken,
        },
      });
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  }

  it.each([
    { label: "missing or unreadable mount", mountToken: "", mountFails: true, envToken: "fake-env-token", expected: "fake-env-token" },
    { label: "empty mount", mountToken: "", mountFails: false, envToken: "fake-env-token", expected: "fake-env-token" },
    { label: "mounted token takes precedence", mountToken: "fake-mounted-token", mountFails: false, envToken: "fake-env-token", expected: "fake-mounted-token" },
  ])("authenticates with $label", ({ mountToken, mountFails, envToken, expected }) => {
    const result = runHelper(mountToken, mountFails, envToken, expected);
    expect(result.status).toBe(0);
    expect(result.stdout).toBe("username=x-access-token\npassword=fake-installation-token\n");
    expect(result.stderr).toBe("");
  });

  it("warns and continues anonymously when neither token source is available", () => {
    const result = runHelper("", true, "", "must-not-call-credential-api");
    expect(result.status).toBe(0);
    expect(result.stdout).toBe("");
    expect(result.stderr).toContain("git-credential-valet: no sandbox token found");
  });
});
