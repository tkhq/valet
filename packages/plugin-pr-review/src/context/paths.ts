/**
 * Path classes the context stage treats as noise (generated, lockfile,
 * vendored, binary, minified) and the paths it treats as risky. The diff
 * ranking and the repository scan use the same rules.
 */
import { matchesGlob } from "./glob.js";

export type NoiseKind = "generated" | "lockfile" | "vendored" | "binary" | "minified" | "snapshot";

const LOCKFILES = new Set([
  "package-lock.json", "pnpm-lock.yaml", "yarn.lock", "bun.lockb", "Cargo.lock", "go.sum", "poetry.lock", "Pipfile.lock",
  "uv.lock", "Gemfile.lock", "composer.lock", "flake.lock", "mix.lock", "pubspec.lock", "Package.resolved", "gradle.lockfile",
]);

const BINARY = /\.(png|jpe?g|gif|webp|ico|bmp|tiff?|pdf|zip|gz|tgz|bz2|xz|7z|jar|war|class|so|dylib|dll|exe|bin|wasm|woff2?|ttf|otf|eot|mp[34]|mov|avi|webm|ogg|wav|psd|sketch|fig|db|sqlite|pyc|o|a)$/i;

/** Why a path is noise for review and context, or undefined when it is source. */
export function noiseKind(path: string): NoiseKind | undefined {
  const base = path.slice(path.lastIndexOf("/") + 1);
  if (LOCKFILES.has(base)) return "lockfile";
  if (/(^|\/)(vendor|third_party|third-party|node_modules|bower_components|\.yarn|Pods)\//.test(path)) return "vendored";
  if (BINARY.test(base)) return "binary";
  if (/\.min\.(js|css)$|\.(js|css)\.map$/.test(base)) return "minified";
  if (/(^|\/)__snapshots__\/|\.snap$/.test(path)) return "snapshot";
  if (
    /\.pb\.go$|\.pb\.gw\.go$|_pb2(_grpc)?\.pyi?$|\.pb\.(ts|js|cc|h|swift)$|_pb\.(ts|js|d\.ts)$|\.gen\.\w+$|_gen\.go$|_generated\.\w+$|\.generated\.\w+$|zz_generated\.\w+\.go$/.test(base) ||
    /(^|\/)(generated|__generated__|gen)\//.test(path) ||
    /(^|\/)dist\/|(^|\/)build\/.*\.js$/.test(path)
  ) {
    return "generated";
  }
  return undefined;
}

/** A first-line marker that tools put in generated files. */
export function looksGenerated(text: string): boolean {
  const head = text.slice(0, 600);
  return /@generated|Code generated .* DO NOT EDIT|DO NOT EDIT\. This file|autogenerated by|This file is automatically generated/i.test(head);
}

/**
 * Words in a path that mark code where a defect costs the most in any
 * codebase: auth, keys and secrets, signing, migrations, access control,
 * payments and webhooks. Matched per path segment part. Stack-specific
 * paths (a team's deploy or rollout config) come from the `riskPaths` setting.
 */
const RISK = /(^|[/_.-])(auth\w*|oauth|session|login|password|passkey|webauthn|credential\w*|token\w*|keys?|keystore|secret\w*|crypto\w*|cipher|encrypt\w*|sign(er|ing|ature)?\w*|migrations?|migrate|schema|iam|rbac|roles?|permission\w*|polic(y|ies)|acl|payment\w*|billing|webhook\w*|sanitiz\w*|escape)([/_.-]|$)/i;

/** Whether a path names risky code: an instruction file, a generic risk word, or one of the team's `riskPaths` globs. */
export function riskyPath(path: string, riskPaths: readonly string[] = []): boolean {
  return instructionPath(path) || RISK.test(path.replace(/([a-z])([A-Z])/g, "$1_$2")) || (riskPaths.length > 0 && matchesGlob(path, riskPaths));
}

/** Convention files read at the repo root and in each directory above a changed path. */
export const NESTED_CONVENTIONS = new Set(["AGENTS.md", "CLAUDE.md"]);
/** Convention files read at the repo root only. */
export const ROOT_CONVENTIONS = new Set(["CONTRIBUTING.md", ".github/CONTRIBUTING.md", "docs/CONTRIBUTING.md", "REVIEWING.md", ".github/copilot-instructions.md", ".cursorrules"]);
export const PLAYBOOK = /(^|\/)playbooks\/.+\.md$/i;

/**
 * Whether a path holds instructions for agents or reviewers: a convention
 * file anywhere in the tree, or a playbook. A PR that changes one is
 * reviewed as code, and the diff budget keeps it.
 */
export function instructionPath(path: string): boolean {
  const base = path.slice(path.lastIndexOf("/") + 1);
  return NESTED_CONVENTIONS.has(base) || ROOT_CONVENTIONS.has(path) || base === "CONTRIBUTING.md" || PLAYBOOK.test(path);
}
