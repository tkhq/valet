/**
 * `--pull-flagged` (TKAI-334): harvest thumbs-rated sessions into the eval
 * corpus. Reads rated sessions straight from the database (see the api's
 * eval-flagged module), extracts one Trajectory per thread, and writes one
 * JSON file per session under `evals/baselines/flagged/`.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import {
  openEvalDataSource,
  readFlaggedSessions,
  type FlaggedSessionExport,
} from "@valet/api/eval-flagged";
import type { MessageEntry, SessionEntry } from "@valet/engine";
import { saveBaseline, type BaselineRecord } from "./baseline.js";
import { extractTrajectory } from "./trajectory.js";
import type { Trajectory } from "./types.js";

export interface PullFlaggedOptions {
  /** Postgres connection string. Wins over pgDataDir. */
  databaseUrl?: string;
  /** Embedded PGlite data dir (the api must not be running against it). */
  pgDataDir?: string;
  /** Which ratings to pull. Default positive (the benchmark corpus). */
  rating?: "positive" | "negative";
  /** Output dir; files land in `<dir>/flagged/`. */
  baselinesDir: string;
  now?: () => Date;
}

export interface FlaggedPullFile {
  sessionId: string;
  rating: "positive" | "negative";
  title: string | null;
  ratedAt: number;
  pulledAt: string;
  trajectories: Trajectory[];
}

function firstUserContent(entries: SessionEntry[]): string {
  const user = entries.find((e): e is MessageEntry => e.type === "message" && e.role === "user");
  return user?.content ?? "";
}

function firstAssistantModel(entries: SessionEntry[]): string {
  const assistant = entries.find(
    (e): e is MessageEntry => e.type === "message" && e.role === "assistant" && e.model !== undefined,
  );
  return assistant?.model ?? "unknown";
}

/** Build the per-session export file from raw thread entries. */
export function flaggedPullFile(
  flagged: FlaggedSessionExport,
  pulledAt: string,
): FlaggedPullFile {
  const trajectories = flagged.threads.map(({ threadId, entries }) =>
    extractTrajectory({
      caseId: `flagged:${flagged.sessionId}:${threadId}`,
      prompt: firstUserContent(entries),
      model: firstAssistantModel(entries),
      durationMs: 0,
      entries,
      metadata: { sessionId: flagged.sessionId, threadId, rating: flagged.rating },
    }),
  );
  return {
    sessionId: flagged.sessionId,
    rating: flagged.rating,
    title: flagged.title,
    ratedAt: flagged.ratedAt,
    pulledAt,
    trajectories,
  };
}

/**
 * Baseline records derived from one flagged session: one per thread, in
 * the SAME shape `loadLatestBaseline` reads, so a harvested trajectory is
 * immediately usable as a `judge_equivalence` baseline for the case id
 * `flagged-{sessionId}-{threadId}`.
 */
export function flaggedBaselineRecords(flagged: FlaggedSessionExport, pulledAt: string): BaselineRecord[] {
  const file = flaggedPullFile(flagged, pulledAt);
  return file.trajectories.map((trajectory) => ({
    // Path-safe case id (the trajectory's own caseId keeps the colon form
    // for provenance in metadata).
    caseId: `flagged-${flagged.sessionId}-${(trajectory.metadata?.threadId as string) ?? "t"}`,
    model: trajectory.model,
    savedAt: pulledAt,
    // A 👍 session is a known-good baseline; a 👎 one is a known-bad
    // reference for regression cases.
    status: flagged.rating === "positive" ? "pass" : "fail",
    trajectory,
  }));
}

/**
 * A runnable case-YAML scaffold for one harvested trajectory: the original
 * prompt plus a judge_equivalence check against the harvested baseline.
 * Written beside the baseline as `<case-id>.yaml.example` — a human
 * reviews and moves it into `evals/cases/` (harvested prompts may carry
 * private context that must not land in a tracked case verbatim).
 */
export function flaggedCaseScaffold(record: BaselineRecord): string {
  const promptBlock = record.trajectory.prompt
    .split("\n")
    .map((l) => `      ${l}`)
    .join("\n");
  return [
    `# Scaffold generated by --pull-flagged from session ${String(record.trajectory.metadata?.sessionId ?? "")}.`,
    "# Review the prompt for private context, then move into evals/cases/.",
    `id: ${record.caseId}`,
    "turns:",
    "  - role: user",
    "    content: |-",
    promptBlock,
    "checks:",
    "  - type: judge_equivalence",
    "  - type: no_errors",
    "",
  ].join("\n");
}

/** Pull rated sessions and write them under `<baselinesDir>`. */
export async function pullFlagged(opts: PullFlaggedOptions): Promise<{ files: string[] }> {
  const src = await openEvalDataSource({
    ...(opts.databaseUrl !== undefined ? { databaseUrl: opts.databaseUrl } : {}),
    ...(opts.pgDataDir !== undefined ? { pgDataDir: opts.pgDataDir } : {}),
  });
  try {
    const flagged = await readFlaggedSessions(src, { rating: opts.rating ?? "positive" });
    const rawDir = join(opts.baselinesDir, "flagged");
    await mkdir(rawDir, { recursive: true });
    const pulledAt = (opts.now ?? (() => new Date()))().toISOString();
    const files: string[] = [];
    for (const session of flagged) {
      // The raw session export, for humans and future tooling.
      const file = flaggedPullFile(session, pulledAt);
      const rawPath = join(rawDir, `${session.sessionId}.json`);
      await writeFile(rawPath, `${JSON.stringify(file, null, 2)}\n`, "utf8");
      files.push(rawPath);
      // Loader-compatible baselines + a runnable case scaffold per thread.
      for (const record of flaggedBaselineRecords(session, pulledAt)) {
        files.push(await saveBaseline(opts.baselinesDir, record));
        const scaffoldPath = join(rawDir, `${record.caseId}.yaml.example`);
        await writeFile(scaffoldPath, flaggedCaseScaffold(record), "utf8");
        files.push(scaffoldPath);
      }
    }
    return { files };
  } finally {
    await src.close();
  }
}
